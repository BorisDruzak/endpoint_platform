import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'America/New_York' }) // Report timezone must not follow the browser.

for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
  test(`synthetic employee analytics through real API at ${viewport.width}px`, async ({ page }, testInfo) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.setViewportSize(viewport)
    await page.goto('/admin/login')
    await page.getByLabel('Имя пользователя').fill('console-e2e')
    await page.getByLabel('Пароль').fill('console-e2e-password')
    await page.getByRole('button', { name: 'Войти' }).click()
    await page.getByRole('link', { name: 'Аналитика активности', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Аналитика активности' })).toBeVisible()
    await page.getByRole('combobox', { name: 'Период', exact: true }).selectOption('7d')
    await page.getByLabel('Поиск', { exact: true }).fill('Synthetic.Employee')
    await page.getByLabel('Сортировка').selectOption('last_observed')
    await page.getByRole('button', { name: /EXAMPLE.*Synthetic.Employee/ }).click()
    await expect(page.getByRole('heading', { name: 'Приложения', exact: true })).toBeVisible()
    await expect(page.getByRole('progressbar', { name: 'Microsoft Word', exact: true })).toBeVisible()
    await expect(page.getByRole('progressbar', { name: 'Microsoft Excel', exact: true })).toBeVisible()
    await expect(page.getByRole('progressbar', { name: 'Google Chrome', exact: true })).toBeVisible()
    const segment = page.getByRole('button', { name: /ACTIVE winword.exe/ }).first()
    await segment.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByText('winword.exe · Тестовый компьютер', { exact: true })).toBeVisible()
    await expect(page.getByText(/Период наблюдения:/)).toBeVisible()
    const previousDay = page.locator('.analytics-days button').nth(5)
    await previousDay.click()
    await expect(page).toHaveURL(/day=/)
    await expect(page.getByRole('heading', { name: 'Приложения', exact: true })).toBeVisible()
    await page.locator('.analytics-days button').last().click()
    await page.getByLabel('Часовой пояс').selectOption('UTC')
    await expect(page).toHaveURL(/timezone=UTC/)
    await page.getByRole('combobox', { name: 'Период', exact: true }).selectOption('30d')
    await expect(page.locator('.analytics-days button')).toHaveCount(30)
    await page.getByRole('combobox', { name: 'Период', exact: true }).selectOption('custom')
    await expect(page.getByLabel('С', { exact: true })).not.toHaveValue('')
    await expect(page.getByLabel('По', { exact: true })).not.toHaveValue('')
    await page.getByRole('button', { name: 'К таблице', exact: true }).click()
    await expect(page.getByRole('columnheader', { name: 'Сотрудник', exact: true })).toBeVisible()
    expect(new URL(page.url()).searchParams.get('search')).toBe('Synthetic.Employee')
    expect(new URL(page.url()).searchParams.get('period')).toBe('custom')
    await page.getByRole('button', { name: 'Обновить', exact: true }).click()
    await expect(page.getByRole('button', { name: /EXAMPLE.*Synthetic.Employee/ })).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Поиск', { exact: true })).toHaveValue('Synthetic.Employee')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('button', { name: /EXAMPLE.*Synthetic.Employee/ }).click()
    await page.getByRole('heading', { name: 'Приложения', exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath(`analytics-${viewport.width}.png`), fullPage: true })
    await page.getByRole('button', { name: 'К таблице', exact: true }).click()
    await page.getByLabel('Поиск', { exact: true }).fill('Лабораторный')
    await expect(page.getByRole('cell', { name: /^Учётная запись неизвестна/ })).toBeVisible()
    await expect(page.getByText('Нет актуального наблюдения', { exact: true })).toBeVisible()
    expect(errors).toEqual([])
  })
}
