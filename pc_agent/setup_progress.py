@dataclass(frozen=True, slots=True)
class SetupProgress:
    stage: str
    status: str
    detail: str = "STARTED"
    code: int | None = None

    def __post_init__(self):
        if self.stage not in STAGES:
            object.__setattr__(self, "stage", "SETUP")
        if self.status not in {"running", "waiting", "success", "error"}:
            object.__setattr__(self, "status", "error")
        if self.detail not in MESSAGES:
            object.__setattr__(self, "detail", "UNKNOWN_ERROR")

    @property
    def title(self):
        return STAGES[self.stage]

    @property
    def message(self):
        return MESSAGES[self.detail]


def emit_progress(
    observer: Callable[[SetupProgress], None] | None,
    stage: str,
    status: str,
    detail: str = "STARTED",
    code: int | None = None,
):
    if observer is not None:
        try:
            observer(SetupProgress(stage, status, detail, code))
        except Exception:
            # A view/diagnostic failure must never interrupt a native transaction.
            pass
